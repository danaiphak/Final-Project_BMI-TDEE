<?php
// ----------------------------------------------------------------------
// 1. การจัดการ Session
// ----------------------------------------------------------------------
// ตรวจสอบว่าระบบเริ่มใช้งาน Session หรือยัง หากยังไม่มีให้เรียกใช้ session_start()
if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

// ----------------------------------------------------------------------
// 2. ตั้งค่าข้อมูลการเชื่อมต่อฐานข้อมูล MySQL
// ----------------------------------------------------------------------
$host = "localhost";        // ชื่อโฮสต์ของระบบฐานข้อมูล (สำหรับจำลองในเครื่องใช้ localhost)
$username = "root";         // ชื่อผู้ใช้ของฐานข้อมูล
$password = "";             // รหัสผ่านเข้าฐานข้อมูล (ปกติ XAMPP ค่าเริ่มต้นจะเป็นค่าว่าง)
$database = "userdb_bmi&tdee"; // ชื่อฐานข้อมูลที่ใช้งาน

// ----------------------------------------------------------------------
// 3. เริ่มต้นการเชื่อมต่อฐานข้อมูลด้วย MySQLi
// ----------------------------------------------------------------------
$conn = new mysqli($host, $username, $password, $database);

// ตรวจสอบข้อผิดพลาดในการเชื่อมต่อฐานข้อมูล
if ($conn->connect_error) {
    // หากเชื่อมต่อไม่สำเร็จ ให้หยุดการทำงานทันทีและแสดงข้อความแจ้งเตือนข้อผิดพลาด
    die("Database connection failed: " . $conn->connect_error);
}

// กำหนดชุดตัวอักษร (Character Set) ให้รองรับภาษาไทยแบบ utf8mb4
$conn->set_charset("utf8mb4");

// ----------------------------------------------------------------------
// 4. ระบบความปลอดภัย CSRF (Cross-Site Request Forgery Protection)
// ----------------------------------------------------------------------

// สร้าง CSRF Token แบบสุ่มเพื่อความปลอดภัย ประจำ Session หากยังไม่มี Token นี้
if (empty($_SESSION['csrf_token'])) {
    // สุ่มค่าไบต์ปลอดภัยขนาด 32 ไบต์ แล้วแปลงเป็นข้อความฐาน 16 (Hex)
    $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
}

/**
 * ฟังก์ชันสำหรับตรวจสอบความถูกต้องของ CSRF Token ที่ส่งมาจากฟอร์ม POST
 * 
 * @param string $token Token ที่ผู้ใช้ส่งมาจากฟอร์ม
 * @return bool คืนค่า true หาก Token ตรงกัน หรือ false หากไม่ถูกต้อง
 */
function verify_csrf_token($token) {
    // ใช้ hash_equals() เปรียบเทียบ Token เพื่อป้องกันการโจมตีประเภท Timing Attack
    return isset($_SESSION['csrf_token']) && hash_equals($_SESSION['csrf_token'], $token);
}
?>