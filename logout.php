<?php
// นำเข้าไฟล์เชื่อมต่อฐานข้อมูลและการจัดการ Session
require_once "db.php";

// ----------------------------------------------------------------------
// 1. ล้างข้อมูลใน Session ทั้งหมด
// ----------------------------------------------------------------------
// กำหนดตัวแปร $_SESSION ให้เป็นอาร์เรย์ว่าง เพื่อล้างค่าข้อมูลผู้ใช้ (เช่น user_id, username) ออกจากหน่วยความจำ
$_SESSION = [];

// ----------------------------------------------------------------------
// 2. ทำลายคุกกี้ที่ใช้เก็บบล็อก Session ID บนเบราว์เซอร์
// ----------------------------------------------------------------------
// ตรวจสอบว่าระบบเปิดใช้งานการใช้ Cookies ในการเก็บ Session ID หรือไม่
if (ini_get("session.use_cookies")) {
    // ดึงพารามิเตอร์การตั้งค่าคุกกี้ปัจจุบัน (เช่น path, domain, secure, httponly)
    $params = session_get_cookie_params();
    
    // ตั้งค่าคุกกี้ Session (PHPSESSID) ให้หมดอายุทันที (ตั้งเวลาเป็นอดีต: time() - 42000)
    // เพื่อสั่งให้เบราว์เซอร์ลบไฟล์คุกกี้ Session นั้นทิ้ง
    setcookie(
        session_name(),
        "",
        time() - 42000,
        $params["path"],
        $params["domain"],
        $params["secure"],
        $params["httponly"]
    );
}

// ----------------------------------------------------------------------
// 3. ทำลาย Session บนเซิร์ฟเวอร์
// ----------------------------------------------------------------------
// สั่งทำลายไฟล์ Session ที่จัดเก็บอยู่บนเซิร์ฟเวอร์อย่างสมบูรณ์
session_destroy();

// ----------------------------------------------------------------------
// 4. ส่งผู้ใช้กลับไปยังหน้าแรก (Index)
// ----------------------------------------------------------------------
// ส่ง HTTP Header เปลี่ยนทิศทางพาผู้ใช้กลับไปยังหน้าแรก
header("Location: index.php");
exit; // ยุติการทำงานของสคริปต์ PHP ทันที
?>